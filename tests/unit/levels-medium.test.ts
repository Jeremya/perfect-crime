// Tests for story X6 — the 10 medium heists (levels/medium/m1.lvl … m10.lvl).
//
// The "medium" band is pinned here (tasks/X6.md): par 16-24, 2-3 guards,
// 0-1 camera, 0 lasers, maxPauses 2-3, standard 8x12 map, one S/L/E each,
// patrol periods dividing 24. Per level, straight from the task:
//   - the .lvl passes the build gate (validateLevelSource: periods divide 24,
//     start not seen at tick 0, solvable within 64 ticks);
//   - the declared par equals the solver par and a winning plan exists
//     (run(solver.plan) → won in exactly "par" ticks);
//   - the medium band holds (par, guards, cameras, lasers, maxPauses, grid);
//   - the level's mechanic moment is pinned: m1 both guards pingpong,
//     m2 mandatory pause (minPauses >= 1), m3 one camera, m4 a loop patrol,
//     m5 two guards sharing a patrol cell, m6 a walled corridor row,
//     m7 pause + camera (minPauses >= 1, 1 camera), m8 three guards with
//     staggered phases, m9 tight par (>= 23) on a long forced route,
//     m10 signature-lite (non-empty moment, type stays "normal");
//   - quality bar: at least two plausible routes (optimalPlans >= 2) and a
//     tension >= 2 (the optimal plan grazes a cone at least twice);
//   - the compiled levels/levels.json carries the 10 medium levels as
//     "medium/mN" with the same pars (generated by `npm run validate`,
//     never hand-edited).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { parseLevel, YAP_GRID_HEIGHT, YAP_GRID_WIDTH, type YapLevel } from '../../src/core/level';
import { run } from '../../src/core/sim';
import { solveLevel } from '../../src/core/solver';
import { validateLevelSource } from '../../tools/validate';
import { YAP_LEVELS_JSON_PATH } from '../../tools/compile-levels';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const MEDIUM_DIR = join(ROOT, 'levels/medium');

/** The X6 medium table: one mechanic moment per level, increasing pressure. */
interface YapMediumSpec {
  readonly file: string;
  readonly guards: number;
  readonly cameras: number;
  /** m1: every guard is a back-and-forth (pingpong) patrol. */
  readonly allPingpong?: boolean;
  /** m2, m7: the optimal plan cannot avoid a pause. */
  readonly requiresPause?: boolean;
  /** m4: at least one guard patrols a closed loop. */
  readonly hasLoop?: boolean;
  /** m5: two guards share a patrol cell (they cross). */
  readonly crossing?: boolean;
  /** m6: the map has a full wall row with a single gap (the corridor). */
  readonly corridor?: boolean;
  /** m8: phases of the guards are pairwise distinct (staggered). */
  readonly staggered?: boolean;
  /** m9: tight par on a long forced route. */
  readonly parMin?: number;
  /** m10: signature-lite — non-empty moment, type stays normal. */
  readonly signatureLite?: boolean;
}

const YAP_MEDIUMS: readonly YapMediumSpec[] = [
  { file: 'm1.lvl', guards: 2, cameras: 0, allPingpong: true },
  { file: 'm2.lvl', guards: 2, cameras: 0, requiresPause: true },
  { file: 'm3.lvl', guards: 2, cameras: 1 },
  { file: 'm4.lvl', guards: 2, cameras: 0, hasLoop: true },
  { file: 'm5.lvl', guards: 3, cameras: 0, crossing: true },
  { file: 'm6.lvl', guards: 2, cameras: 0, corridor: true },
  { file: 'm7.lvl', guards: 2, cameras: 1, requiresPause: true },
  { file: 'm8.lvl', guards: 3, cameras: 0, staggered: true },
  { file: 'm9.lvl', guards: 2, cameras: 0, parMin: 23 },
  { file: 'm10.lvl', guards: 3, cameras: 1, signatureLite: true },
];

function loadMedium(spec: YapMediumSpec): YapLevel {
  const file = join(MEDIUM_DIR, spec.file);
  const source = readFileSync(file, 'utf8');
  const check = validateLevelSource(source, file);
  expect(check.issues, `validate gate issues for ${spec.file}`).toEqual([]);
  expect(check.level).not.toBeNull();
  return parseLevel(source, file);
}

describe('X6 — medium heists: band, gate, golden and mechanic moments', () => {
  for (const spec of YAP_MEDIUMS) {
    describe(`${spec.file}`, () => {
      const level = loadMedium(spec);

      it('is a normal heist on the standard 8x12 map with one S, one L, one E', () => {
        expect(level.type).toBe('normal');
        expect(level.width).toBe(YAP_GRID_WIDTH);
        expect(level.height).toBe(YAP_GRID_HEIGHT);
        expect(level.map).toHaveLength(YAP_GRID_HEIGHT);
        for (const row of level.map) expect(row).toHaveLength(YAP_GRID_WIDTH);
        const marks = level.map.map((row) => [...row].filter((c) => 'SLE'.includes(c)).join(''));
        expect(marks.join('')).toHaveLength(3);
      });

      it('holds the medium band: par 16-24, 2-3 guards, <=1 camera, 0 lasers, maxPauses 2-3', () => {
        expect(level.par).toBeGreaterThanOrEqual(16);
        expect(level.par).toBeLessThanOrEqual(24);
        if (spec.parMin !== undefined) expect(level.par).toBeGreaterThanOrEqual(spec.parMin);
        expect(level.guards.length).toBe(spec.guards);
        expect(level.guards.length).toBeGreaterThanOrEqual(2);
        expect(level.guards.length).toBeLessThanOrEqual(3);
        expect(level.cameras).toHaveLength(spec.cameras);
        expect(level.cameras.length).toBeLessThanOrEqual(1);
        expect(level.lasers).toHaveLength(0);
        expect(level.maxPauses).toBeGreaterThanOrEqual(2);
        expect(level.maxPauses).toBeLessThanOrEqual(3);
      });

      it('has a declared par equal to the solver par', () => {
        expect(solveLevel(level).par).toBe(level.par);
      });

      it('golden: the optimal plan wins in exactly "par" ticks', () => {
        const solved = solveLevel(level);
        const result = run(level, solved.plan);
        expect(result.outcome.kind).toBe('won');
        if (result.outcome.kind === 'won') expect(result.outcome.tick).toBe(level.par);
        expect(result.frames).toHaveLength(level.par + 1); // tick 0 + one frame per tick
      });

      it('leaves at least two plausible routes and grazes a cone (optimalPlans >= 2, tension >= 2)', () => {
        const solved = solveLevel(level);
        expect(solved.optimalPlans).toBeGreaterThanOrEqual(2);
        expect(solved.tension).toBeGreaterThanOrEqual(2);
      });

      if (spec.allPingpong) {
        it('m1: every guard is a back-and-forth (pingpong) patrol', () => {
          for (const guard of level.guards) expect(guard.mode).toBe('pingpong');
        });
      }

      if (spec.requiresPause) {
        it('the optimal plan cannot avoid a pause (minPauses >= 1)', () => {
          expect(solveLevel(level).minPauses).toBeGreaterThanOrEqual(1);
        });
      }

      if (spec.hasLoop) {
        it('m4: at least one guard patrols a closed loop', () => {
          expect(level.guards.some((g) => g.mode === 'loop')).toBe(true);
        });
      }

      if (spec.crossing) {
        it('m5: two guards share a patrol cell (they cross paths)', () => {
          const cellsOf = (g: YapLevel['guards'][number]): string[] =>
            g.route.map((c) => `${c.x},${c.y}`);
          const shared = level.guards.flatMap((a) =>
            level.guards.flatMap((b) =>
              a === b ? [] : cellsOf(a).filter((c) => cellsOf(b).includes(c)),
            ),
          );
          expect(shared.length).toBeGreaterThanOrEqual(1);
        });
      }

      if (spec.corridor) {
        it('m6: a full wall row with a single gap forces the corridor', () => {
          const wallRows = level.map.filter((row) => row.split('').filter((c) => c === '#').length >= 7);
          expect(wallRows.length).toBeGreaterThanOrEqual(1);
        });
      }

      if (spec.staggered) {
        it('m8: the three guards have pairwise distinct phases', () => {
          const phases = level.guards.map((g) => g.phase);
          expect(new Set(phases).size).toBe(phases.length);
        });
      }

      if (spec.signatureLite) {
        it('m10: signature-lite — non-empty moment, type stays normal', () => {
          expect(level.moment.length).toBeGreaterThan(0);
          expect(level.type).toBe('normal');
        });
      }
    });
  }

  it('levels/levels.json carries the 10 medium levels as medium/mN with the same pars', () => {
    const bundle = JSON.parse(readFileSync(join(ROOT, YAP_LEVELS_JSON_PATH), 'utf8')) as {
      levels: { id: string; level: YapLevel }[];
    };
    const byId = new Map(bundle.levels.map((e) => [e.id, e.level]));
    for (const spec of YAP_MEDIUMS) {
      const id = `medium/${spec.file.slice(0, -'.lvl'.length)}`;
      const compiled = byId.get(id);
      expect(compiled, `levels.json entry ${id}`).toBeDefined();
      if (compiled === undefined) continue;
      expect(compiled.par).toBe(loadMedium(spec).par);
      expect(compiled.type).toBe('normal');
    }
  });
});
