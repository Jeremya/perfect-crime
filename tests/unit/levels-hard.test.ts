// Tests for story X7 — the 10 hard heists (levels/hard/h1.lvl … h10.lvl).
//
// The "hard" band is pinned here (tasks/X7.md): par 25-34, exactly 3 guards,
// 1-2 cameras, 0-1 laser, maxPauses 3, standard 8x12 map, one S/L/E each,
// patrol periods dividing 24. Per level, straight from the task:
//   - the .lvl passes the build gate (validateLevelSource: periods divide 24,
//     start not seen at tick 0, solvable within 64 ticks);
//   - the declared par equals the solver par and a winning plan exists
//     (run(solver.plan) → won in exactly "par" ticks);
//   - the hard band holds (par, guards, cameras, lasers, maxPauses, grid);
//   - the level's mechanic moment is pinned: h1 laser timing (1 laser, the
//     golden plan steps on a laser cell, minPauses >= 1), h2 camera + laser
//     (1 camera, 1 laser, minPauses >= 2), h3 three guards pairwise crossing
//     (every pair shares a route cell), h4 pause chain (minPauses >= 2),
//     h5 corridor under sweep + laser (laser row between two wall rows,
//     minPauses >= 2), h6 tight par (>= 33), h7 loop + pingpong combined (a
//     loop guard shares a cell with a pingpong guard), h8 double camera
//     (2 cameras), h9 long route + laser (1 laser, par >= 29), h10 signature
//     hard (non-empty moment, type stays "normal", 2 cameras, 1 laser);
//   - quality bar: at least two plausible routes (optimalPlans >= 2) and a
//     tension >= 2 (the optimal plan grazes a cone at least twice);
//   - the compiled levels/levels.json carries the 10 hard levels as
//     "hard/hN" with the same pars (generated by `npm run validate`,
//     never hand-edited).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { parseLevel, YAP_GRID_HEIGHT, YAP_GRID_WIDTH, type YapLevel } from '../../src/core/level';
import { run } from '../../src/core/sim';
import { solveLevel } from '../../src/core/solver';
import { validateLevelSource } from '../../tools/validate';
import { YAP_LEVELS_JSON_PATH } from '../../tools/compile-levels';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const HARD_DIR = join(ROOT, 'levels/hard');

/** The X7 hard table: one mechanic moment per level, increasing pressure. */
interface YapHardSpec {
  readonly file: string;
  readonly cameras: number;
  readonly lasers: number;
  /** h1, h2, h5, h9, h10: the golden plan steps on a laser cell. */
  readonly planVisitsLaser?: boolean;
  /** h1, h2, h4, h5: the optimal plan cannot avoid pauses. */
  readonly requiresPause?: number;
  /** h3: every pair of guards shares at least one route cell. */
  readonly pairwiseCrossing?: boolean;
  /** h5: the laser row sits between two wall rows (the corridor). */
  readonly corridorLaser?: boolean;
  /** h6, h9: tight/long par floor. */
  readonly parMin?: number;
  /** h7: a loop guard shares a cell with a pingpong guard. */
  readonly loopMeetsPingpong?: boolean;
  /** h8: exactly two cameras. */
  readonly doubleCamera?: boolean;
  /** h10: signature hard — non-empty moment, type stays normal. */
  readonly signatureHard?: boolean;
}

const YAP_HARDS: readonly YapHardSpec[] = [
  { file: 'h1.lvl', cameras: 1, lasers: 1, planVisitsLaser: true, requiresPause: 1 },
  { file: 'h2.lvl', cameras: 1, lasers: 1, planVisitsLaser: true, requiresPause: 2 },
  { file: 'h3.lvl', cameras: 1, lasers: 0, pairwiseCrossing: true },
  { file: 'h4.lvl', cameras: 1, lasers: 0, requiresPause: 2 },
  { file: 'h5.lvl', cameras: 1, lasers: 1, requiresPause: 2, corridorLaser: true },
  { file: 'h6.lvl', cameras: 1, lasers: 0, parMin: 33 },
  { file: 'h7.lvl', cameras: 1, lasers: 0, loopMeetsPingpong: true },
  { file: 'h8.lvl', cameras: 2, lasers: 0, doubleCamera: true },
  { file: 'h9.lvl', cameras: 1, lasers: 1, planVisitsLaser: true, parMin: 29 },
  { file: 'h10.lvl', cameras: 2, lasers: 1, planVisitsLaser: true, signatureHard: true },
];

function loadHard(spec: YapHardSpec): YapLevel {
  const file = join(HARD_DIR, spec.file);
  const source = readFileSync(file, 'utf8');
  const check = validateLevelSource(source, file);
  expect(check.issues, `validate gate issues for ${spec.file}`).toEqual([]);
  expect(check.level).not.toBeNull();
  return parseLevel(source, file);
}

/** True when some frame of the run has the thief standing on a laser cell. */
function planVisitsLaser(level: YapLevel, plan: readonly string[]): boolean {
  const { frames } = run(level, plan as never);
  return frames.some((f) =>
    level.lasers.some((l) => l.cells.some((c) => c.x === f.thief.x && c.y === f.thief.y)),
  );
}

describe('X7 — hard heists: band, gate, golden and mechanic moments', () => {
  for (const spec of YAP_HARDS) {
    describe(`${spec.file}`, () => {
      const level = loadHard(spec);

      it('is a normal heist on the standard 8x12 map with one S, one L, one E', () => {
        expect(level.type).toBe('normal');
        expect(level.width).toBe(YAP_GRID_WIDTH);
        expect(level.height).toBe(YAP_GRID_HEIGHT);
        expect(level.map).toHaveLength(YAP_GRID_HEIGHT);
        for (const row of level.map) expect(row).toHaveLength(YAP_GRID_WIDTH);
        const marks = level.map.map((row) => [...row].filter((c) => 'SLE'.includes(c)).join(''));
        expect(marks.join('')).toHaveLength(3);
      });

      it('holds the hard band: par 25-34, 3 guards, 1-2 cameras, 0-1 laser, maxPauses 3', () => {
        expect(level.par).toBeGreaterThanOrEqual(25);
        expect(level.par).toBeLessThanOrEqual(34);
        if (spec.parMin !== undefined) expect(level.par).toBeGreaterThanOrEqual(spec.parMin);
        expect(level.guards).toHaveLength(3);
        expect(level.cameras).toHaveLength(spec.cameras);
        expect(level.cameras.length).toBeGreaterThanOrEqual(1);
        expect(level.cameras.length).toBeLessThanOrEqual(2);
        expect(level.lasers).toHaveLength(spec.lasers);
        expect(level.lasers.length).toBeLessThanOrEqual(1);
        expect(level.maxPauses).toBe(3);
      });

      it('has a declared par equal to the solver par', () => {
        expect(solveLevel(level).par).toBe(level.par);
      });

      it('golden: the optimal plan wins in exactly "par" ticks', () => {
        const solved = solveLevel(level);
        const result = run(level, solved.plan);
        expect(result.outcome.kind).toBe('won');
        if (result.outcome.kind === 'won') expect(result.outcome.tick).toBe(level.par);
        expect(result.frames).toHaveLength(level.par + 1); // tick 0 + one frame per tick
      });

      it('leaves at least two plausible routes and grazes a cone (optimalPlans >= 2, tension >= 2)', () => {
        const solved = solveLevel(level);
        expect(solved.optimalPlans).toBeGreaterThanOrEqual(2);
        expect(solved.tension).toBeGreaterThanOrEqual(2);
      });

      if (spec.planVisitsLaser) {
        it('the golden plan steps on a laser cell (the laser is on the route)', () => {
          expect(planVisitsLaser(level, solveLevel(level).plan)).toBe(true);
        });
      }

      if (spec.requiresPause !== undefined) {
        const required = spec.requiresPause;
        it(`the optimal plan needs at least ${required} pause(s) (minPauses)`, () => {
          expect(solveLevel(level).minPauses).toBeGreaterThanOrEqual(required);
        });
      }

      if (spec.pairwiseCrossing) {
        it('h3: every pair of guards shares at least one route cell (they cross)', () => {
          const cellsOf = (g: YapLevel['guards'][number]): string[] =>
            g.route.map((c) => `${c.x},${c.y}`);
          for (let i = 0; i < level.guards.length; i += 1) {
            for (let j = i + 1; j < level.guards.length; j += 1) {
              const a = level.guards[i];
              const b = level.guards[j];
              if (a === undefined || b === undefined) continue;
              const shared = cellsOf(a).filter((c) => cellsOf(b).includes(c));
              expect(shared.length, `guards ${a.id} and ${b.id} share a cell`).toBeGreaterThanOrEqual(1);
            }
          }
        });
      }

      if (spec.corridorLaser) {
        it('h5: the laser row sits between two wall rows (the corridor)', () => {
          const laserRow = level.lasers[0]?.cells[0]?.y;
          expect(laserRow).toBeDefined();
          const wallRows = [laserRow! - 1, laserRow! + 1].filter(
            (y) =>
              y >= 0 &&
              y < level.height &&
              (level.map[y]?.split('').filter((c) => c === '#').length ?? 0) >= 5,
          );
          expect(wallRows.length).toBeGreaterThanOrEqual(2);
        });
      }

      if (spec.loopMeetsPingpong) {
        it('h7: a loop guard shares a cell with a pingpong guard', () => {
          const loops = level.guards.filter((g) => g.mode === 'loop');
          const pings = level.guards.filter((g) => g.mode === 'pingpong');
          expect(loops.length).toBeGreaterThanOrEqual(1);
          expect(pings.length).toBeGreaterThanOrEqual(1);
          const cellsOf = (g: YapLevel['guards'][number]): string[] =>
            g.route.map((c) => `${c.x},${c.y}`);
          const meets = loops.some((l) =>
            pings.some((p) => cellsOf(l).some((c) => cellsOf(p).includes(c))),
          );
          expect(meets).toBe(true);
        });
      }

      if (spec.doubleCamera) {
        it('h8: exactly two cameras', () => {
          expect(level.cameras).toHaveLength(2);
        });
      }

      if (spec.signatureHard) {
        it('h10: signature hard — non-empty moment, type stays normal, 2 cameras + 1 laser', () => {
          expect(level.moment.length).toBeGreaterThan(0);
          expect(level.type).toBe('normal');
          expect(level.cameras).toHaveLength(2);
          expect(level.lasers).toHaveLength(1);
        });
      }
    });
  }

  it('levels/levels.json carries the 10 hard levels as hard/hN with the same pars', () => {
    const bundle = JSON.parse(readFileSync(join(ROOT, YAP_LEVELS_JSON_PATH), 'utf8')) as {
      levels: { id: string; level: YapLevel }[];
    };
    const byId = new Map(bundle.levels.map((e) => [e.id, e.level]));
    for (const spec of YAP_HARDS) {
      const id = `hard/${spec.file.slice(0, -'.lvl'.length)}`;
      const compiled = byId.get(id);
      expect(compiled, `levels.json entry ${id}`).toBeDefined();
      if (compiled === undefined) continue;
      expect(compiled.par).toBe(loadHard(spec).par);
      expect(compiled.type).toBe('normal');
    }
  });
});
