// Tests for story F3 — the 7 daily heists (levels/daily/d1.lvl … d7.lvl).
//
// Per-day golden + solvability, straight from the Gate 1 spec (Content and
// Tests sections):
//   - every daily .lvl passes the build gate (validateLevelSource: periods
//     divide 24, start not seen at tick 0, solvable within 64 ticks);
//   - the declared par is inside the day's target range and equals the
//     solver par;
//   - golden: simulating the solver's optimal plan wins in exactly "par"
//     ticks;
//   - the element mix matches the spec's daily table (D1 2 guards, D2 2
//     guards + 1 camera, D3 2 back-and-forth guards, D4 1 guard + 1 laser,
//     D5 1 camera + 1 laser + 1 guard, D6 3 entities, D7 2 crossing guards +
//     1 camera);
//   - quality bar: at most 4 entities, at least two plausible routes
//     (optimalPlans >= 2), and for the signature heists (D3/D5/D7) a
//     non-empty moment sentence and a tension >= 2 (the optimal plan passes
//     within one cell of a cone at least twice);
//   - D7's one-tick window needs a mandatory pause (minPauses >= 1);
//   - the compiled levels/levels.json carries the same 7 daily levels with
//     the same pars (it is generated by `npm run validate`, never hand-edited).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { parseLevel, type YapLevel } from '../../src/core/level';
import { run } from '../../src/core/sim';
import { solveLevel } from '../../src/core/solver';
import { validateLevelSource } from '../../tools/validate';
import { YAP_LEVELS_JSON_PATH } from '../../tools/compile-levels';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const DAILY_DIR = join(ROOT, 'levels/daily');

/** The spec's daily table (Gate 1 — Content section). */
interface YapDaySpec {
  readonly day: number;
  readonly file: string;
  readonly type: 'normal' | 'signature';
  readonly parMin: number;
  readonly parMax: number;
  readonly guards: number;
  readonly cameras: number;
  readonly lasers: number;
  /** Signature heists: the optimal plan must graze a cone at least twice. */
  readonly signature: boolean;
  /** D7: the one-tick window requires a pause in every optimal plan. */
  readonly requiresPause: boolean;
}

