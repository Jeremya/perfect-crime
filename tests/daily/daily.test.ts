function loadDaily(spec: YapDaySpec): YapLevel {
  const file = join(DAILY_DIR, spec.file);
  const source = readFileSync(file, 'utf8');
  const check = validateLevelSource(source, file);
  expect(check.issues, `validate gate issues for ${spec.file}`).toEqual([]);
  expect(check.level).not.toBeNull();
  return parseLevel(source, file);
}

describe('F3 — daily heists: spec table, gate and golden', () => {
  for (const spec of YAP_DAYS) {
    describe(`day ${spec.day} (${spec.file})`, () => {
      const level = loadDaily(spec);

      it('matches the element mix and type of the spec table', () => {
        expect(level.type).toBe(spec.type);
        expect(level.guards).toHaveLength(spec.guards);
        expect(level.cameras).toHaveLength(spec.cameras);
        expect(level.lasers).toHaveLength(spec.lasers);
        expect(
          level.guards.length + level.cameras.length + level.lasers.length,
        ).toBeLessThanOrEqual(4);
      });

      it('has a declared par inside the target range, equal to the solver par', () => {
        expect(level.par).toBeGreaterThanOrEqual(spec.parMin);
        expect(level.par).toBeLessThanOrEqual(spec.parMax);
        const solved = solveLevel(level);
        expect(solved.par).toBe(level.par);
      });

      it('golden: the optimal plan wins in exactly "par" ticks', () => {
        const solved = solveLevel(level);
        const result = run(level, solved.plan);
        expect(result.outcome.kind).toBe('won');
        if (result.outcome.kind === 'won') expect(result.outcome.tick).toBe(level.par);
        expect(result.frames).toHaveLength(level.par + 1); // tick 0 + one frame per tick
      });

      it('leaves at least two plausible routes (optimalPlans >= 2)', () => {
        expect(solveLevel(level).optimalPlans).toBeGreaterThanOrEqual(2);
      });

      if (spec.signature) {
        it('is a signature heist: moment sentence and tension >= 2', () => {
          expect(level.moment.length).toBeGreaterThan(0);
          expect(solveLevel(level).tension).toBeGreaterThanOrEqual(2);
        });
      }

      if (spec.requiresPause) {
        it('D7: the one-tick window forces a pause in the optimal plan', () => {
          expect(solveLevel(level).minPauses).toBeGreaterThanOrEqual(1);
        });
      }

      if (spec.day === 3) {
        it('D3: both guards are back-and-forth (pingpong) patrols', () => {
          for (const guard of level.guards) expect(guard.mode).toBe('pingpong');
        });
      }

      if (spec.day === 7) {
        it('D7: the two guards cross paths (shared patrol cell)', () => {
          const cellsOf = (g: YapLevel['guards'][number]): string[] =>
            g.route.map((c) => `${c.x},${c.y}`);
          const [a, b] = level.guards;
          expect(a).toBeDefined();
          expect(b).toBeDefined();
          if (a === undefined || b === undefined) return;
          const shared = cellsOf(a).filter((c) => cellsOf(b).includes(c));
          expect(shared.length).toBeGreaterThanOrEqual(1);
        });
      }
    });
  }

  it('levels/levels.json carries the 7 daily levels with the same pars', () => {
    const bundle = JSON.parse(readFileSync(join(ROOT, YAP_LEVELS_JSON_PATH), 'utf8')) as {
      levels: { id: string; level: YapLevel }[];
    };
    const byId = new Map(bundle.levels.map((e) => [e.id, e.level]));
    for (const spec of YAP_DAYS) {
      const id = `daily/${spec.file.slice(0, -'.lvl'.length)}`;
      const compiled = byId.get(id);
      expect(compiled, `levels.json entry ${id}`).toBeDefined();
      if (compiled === undefined) continue;
      expect(compiled.par).toBe(loadDaily(spec).par);
      expect(compiled.type).toBe(spec.type);
    }
  });
});
